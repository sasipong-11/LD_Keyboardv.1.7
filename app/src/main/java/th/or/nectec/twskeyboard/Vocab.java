public class Vocab {
    private String word;
    private String partOfSpeech;
    private String thaiTrans;
    private String engTrans;

    public String getWord() {
        return word;
    }

    public void setWord(String word) {
        this.word = word;
    }

    public String getPartOfSpeech() {
        return partOfSpeech;
    }

    public void setPartOfSpeech(String partOfSpeech) {
        this.partOfSpeech = partOfSpeech;
    }

    public String getThaiTrans() {
        return thaiTrans;
    }

    public void setThaiTrans(String thaiTrans) {
        this.thaiTrans = thaiTrans;
    }

    public String getEngTrans() {
        return engTrans;
    }

    public void setEngTrans(String engTrans) {
        this.engTrans = engTrans;
    }
}
